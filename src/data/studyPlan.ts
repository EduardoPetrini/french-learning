import type { StudyDay, Task } from './types'

function day(
  week: number,
  dayNum: number,
  dayName: string,
  totalMinutes: number,
  focus: string,
  phase: 1 | 2 | 3,
  tasks: Task[]
): StudyDay {
  return { id: `w${week}d${dayNum}`, week, day: dayNum, dayName, totalMinutes, focus, phase, tasks }
}

function task(
  id: string,
  duration: number,
  type: Task['type'],
  title: string,
  description: string,
  url?: string,
  youtubeId?: string
): Task {
  return { id, duration, type, title, description, url, youtubeId }
}

